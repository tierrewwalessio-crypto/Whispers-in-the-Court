    def _judge(self, order: str, what: str, stage: str) -> None:
        fld = self.field or self.first
        if fld is None or not self.live:
            return
        diff = self._difficulty()
        task = PLAN_TASK.format(style=prompts.text("battle_narrator"), field=self._field_text(fld), setting=self._setting(),
                                so_far=self._so_far(), what=what, order=order.strip()[:800], levers=LEVER_TEXT,
                                ruler=self._ruler_line(), difficulty=prompts.DIFFICULTY.get(self.b.cfg.difficulty, ""),
                                lang=self._lang()) + "\n" + prompts.player_block("battles")
        try:
            data = self._ask(task, PLAN_SCHEMA, "votc_battle_plan", 1800, guide="battle_judge")
        except Player2Error as exc:
            self.b.log(f"Battle order not judged: {exc}")
            data = {"soundness": 5, "reading": "", "effects": [], "personal_risk": 0,
                    "summary": order[:200], "watch": ""}
        soundness = max(0, min(10, int(data.get("soundness") or 5)))
        effects = self.clamp(data.get("effects") or [], soundness, diff)
        risk = max(0, min(3, int(data.get("personal_risk") or 0))) if self.ruler_on_field else 0
        lines, fate = self._apply(effects, risk)
        summary = str(data.get("summary") or order)[:240]
        if stage == "plan":
            self.plan = {"summary": summary, "soundness": soundness, "watch": str(data.get("watch") or "")[:400]}
            self.orders.append(f"the plan: {summary}")
        else:
            self.orders.append(f"the ruler's own order: {summary} (judged {soundness}/10)")
            self.reveal.append(f"the ruler's own order ({summary}) - carried out; how well it worked must show "
                               f"from the field, judged {soundness}/10{fate}")
        if fate:
            self.orders[-1] += fate
        self.b.log(f"  battle order judged {soundness}/10: {summary}"
                   + (f" - effects: {', '.join(self._describe(e) for e in effects)}" if effects else ""))
        reading = str(data.get("reading") or "").strip()
        if self.session is not None and self.b.session is self.session:
            if reading:
                self.b._ui("add_line", "", reading)
            self.b._ui("add_note", "The game runs again at the slowest speed. The battle will call you back.")
            self.b._ui("set_busy", "")
            self.b._ui("set_close_label", "To the field")
        self._go(lines)

    def leave(self) -> None:
        """No plan: the general fights as he sees fit; the moments still come."""
        if self.waiting in ("plan", "brief"):
            self.orders.append("the ruler gave no plan and left the battle to the general")
        elif self.waiting == "order":
            self.orders.append("the ruler gave no order at that moment")
        self.waiting = ""
        self._go([])

    def _go(self, lines: list[str]) -> None:
        self.waiting = ""
        self.last_beat = self.field or self.last_beat
        self.b.mail.send(lines + ["votc_battle_go = yes"], label="battle:go")
        if self.over:                           # it ended while the ruler was deciding
            self.waiting = "end"
            self.b._submit(self._finish)

    # ----------------------------------------------------------- the effects
    def clamp(self, raw: list[Any], soundness: int, diff: dict[str, Any]) -> list[dict[str, Any]]:
        """What the AI proposes, made to agree with its own judgement and the difficulty."""
        good_room = 3 if soundness >= 9 else 2 if soundness >= 7 else 1 if soundness >= 4 else 0
        out: list[dict[str, Any]] = []
        for e in raw:
            if not isinstance(e, dict):
                continue
            kind, side = str(e.get("kind", "")), str(e.get("side", "ours"))
            up = str(e.get("direction", "up")) != "down"
            level = max(1, min(3, int(e.get("level") or 1)))
            if kind not in LEVERS and kind not in ("shake", "bleed", "rally"):
                continue
            if side not in ("ours", "theirs"):
                continue
            if kind == "rally":
                side, up = "ours", True
            if kind in ("shake", "bleed"):
                up = True
            good = self._good({"kind": kind, "side": side, "up": up})
            if good:
                if good_room <= 0:
                    continue
                good_room -= 1
                level = min(level, diff["up"])
            else:
                level = min(level, diff["down"])
            out.append({"kind": kind, "side": side, "up": up, "level": level})
            if len(out) >= 3:
                break
        if soundness >= 7 and not any(self._good(e) for e in out):
            out.append({"kind": "morale", "side": "ours", "up": True, "level": 1})
        if soundness <= 3 and not any(not self._good(e) for e in out):
            out.append({"kind": "command", "side": "ours", "up": False, "level": min(2, diff["down"])})
        return out

    @staticmethod
    def _good(e: dict[str, Any]) -> bool:
        """Good for the ruler's side."""
        if e["kind"] in ("shake", "bleed"):
            return e["side"] == "theirs"
        if e["kind"] == "rally":
            return True
        return e["up"] == (e["side"] == "ours")

    @staticmethod
    def _describe(e: dict[str, Any]) -> str:
        return f"{e['kind']} {'+' if e['up'] else '-'}{e['level']} ({e['side']})"

    def _apply(self, effects: list[dict[str, Any]], risk: int) -> tuple[list[str], str]:
        """The mail lines for these effects, and what befell the ruler, if anything."""
        lines = []
        for e in effects:
            lv = e["level"]
            if e["kind"] in LEVERS:
                key = modifier_key(e["kind"], e["up"], lv)
                if e["side"] == "ours":
                    lines.append(f"votc_battle_mod = {{ mod = {key} days = {OWN_DAYS} }}")
                else:
                    lines.append(f"votc_battle_foe_mod = {{ mod = {key} days = {FOE_DAYS} }}")
            elif e["kind"] == "shake":
                lines.append(f"votc_battle_shake_{'own' if e['side'] == 'ours' else 'foe'} = {{ p = {SHAKE[lv - 1]} }}")
            elif e["kind"] == "bleed":
                lines.append(f"votc_battle_bleed_{'own' if e['side'] == 'ours' else 'foe'} = {{ p = {BLEED[lv - 1]} }}")
            elif e["kind"] == "rally":
                lines.append(f"votc_battle_rally = {{ p = {RALLY[lv - 1]} }}")
        fate = ""
        if risk and self.ruler_on_field:
            danger = self._difficulty()["risk"]
            roll = random.random()
            if roll < FALL[risk] * danger:
                lines.append("votc_battle_fall_ruler = yes")
                fate = " - AND THE RULER FELL: struck down in the fighting and killed"
            elif roll < (FALL[risk] + WOUND[risk]) * danger:
                lines.append("votc_battle_wound_ruler = yes")
                fate = " - and the ruler was wounded in the fighting (not mortally)"
            if risk >= 2 and "fall" not in fate:
                lines.append(f"votc_battle_rally = {{ p = {RALLY[0]} }}")      # the men saw the ruler among them
        return lines, fate

    # --------------------------------------------------------------- moments
    def _moment_due(self, fld: Field) -> bool:
        if len(self.moments) >= MAX_MOMENTS or self.last_beat is None:
            return False
        hours = _hours(fld.date) - _hours(self.last_beat.date)
        if hours <= 0:
            return False
        us, them = fld.sides(self.ours)
        was_us, was_them = self.last_beat.sides(self.ours)
        big = 0
        for a, b in ((was_us, us), (was_them, them)):
            if a.morale is not None and b.morale is not None and a.morale - b.morale >= 0.15:
                big += 1
            if a.reserve and b.reserve is not None and b.reserve < a.reserve * 0.5:
                big += 1
            for wing in ("left", "center", "right"):
                was, now = getattr(a, wing), getattr(b, wing)
                if was and (now is None or now < was * 0.35):
                    big += 1
            if b.morale is not None and b.morale < 0.25 and (a.morale or 1) >= 0.25:
                big += 2                     # the edge of a rout: the last chance to act
        if not self.moments:
            return hours >= 24 or big >= 1           # the first clash
        if big >= 2:
            return hours >= 6
        if big:
            return hours >= 24
        return hours >= 72                            # a long grind: the battle needs its ruler again

    def _moment(self, fld: Field) -> None:
        if not self.live:
            return
        diff = self._difficulty()
        first = not self.moments
        focus = ("the first clash - the lines meet; how the plan survives contact with the enemy."
                 if first else "the battle has turned a corner since the last report: tell what changed and "
                               "what now hangs in the balance.")
        reveal = ""
        if self.reveal:
            reveal = "HOW THE LAST ORDERS WENT (secret until now - this moment must show it on the field):\n" + \
                     "\n".join(f"- {r}" for r in self.reveal)
        task = MOMENT_TASK.format(
            style=prompts.text("battle_narrator"), hours=fld.date, field=self._field_text(fld), moved=self._moved(fld),
            setting=self._setting(), so_far=self._so_far(), reveal=reveal, focus=focus,
            reveal_rule=("Begin with what came of the last orders, shown not told." if reveal else ""),
            levers=LEVER_TEXT, ruler=self._ruler_line(),
            difficulty=prompts.DIFFICULTY.get(self.b.cfg.difficulty, ""), lang=self._lang(),
            player=prompts.player_block("battles", "narration", "avoid"))
        try:
            data = self._ask(task, MOMENT_SCHEMA, "votc_battle_moment", 3200, guide="battle_moment")
        except Player2Error as exc:
            self.b.log(f"Battle moment not written: {exc} - the battle runs on.")
            self._go([])
            return
        if self.over:                           # it ended before the moment was written
            self._go([])
            return
        options = [o for o in (data.get("options") or []) if isinstance(o, dict) and str(o.get("label", "")).strip()]
        if len(options) < 3 or not str(data.get("body") or "").strip():
            self.b.log("Battle moment incomplete - the battle runs on.")
            self._go([])
            return
        self.reveal = []
        moment = {"date": fld.date, "title": str(data.get("title") or self.title)[:70],
                  "body": str(data.get("body") or "").strip()[:2400], "options": options[:3], "field": fld}
        self.moments.append(moment)
        loc = {"votc_bt_title": moment["title"], "votc_bt_body": with_gist(data.get("gist"), moment["body"])}
        for i, o in enumerate(moment["options"], 1):
            loc[f"votc_bt_opt{i}"] = str(o.get("label")).strip()[:120]
        self.last_beat = fld
        self.waiting = "choice"
        self.b.mail.send(["votc_battle_moment = yes"], loc=loc, label="battle:moment")
        self.b.log(f"  battle moment: {moment['title']}")
        if self.session is not None and self.b.session is self.session:
            self.b._ui("close")
            self.b.session = None
        self.session = None

    def on_choice(self, n: int) -> None:
        """The player answered a moment of the battle (1-3, or 4: in person)."""
        if not self.live or self.waiting != "choice" or not self.moments:
            return
        moment = self.moments[-1]
        if n == 4:
            self._open_order(moment)
            return
        if not 1 <= n <= len(moment["options"]):
            self.leave()
            return
        opt = moment["options"][n - 1]
        diff = self._difficulty()
        chance = max(5, min(95, int(opt.get("chance") or 50) + diff["luck"]))
        us, _ = (self.field or moment["field"]).sides(self.ours)
        if us.mil is not None:
            mil = us.mil if us.mil > 10 else us.mil * 10
            chance = max(5, min(95, chance + int((mil - 50) / 6)))
        worked = random.random() * 100 < chance
        case = opt.get("success" if worked else "failure") or {}
        soundness = 8 if worked else 2
        effects = self.clamp(case.get("effects") or [], soundness, diff)
        risk = max(0, min(3, int(opt.get("personal_risk") or 0))) if self.ruler_on_field else 0
        lines, fate = self._apply(effects, risk)
        label = str(opt.get("label") or "")
        note = str(case.get("note") or "")
        self.orders.append(f"at '{moment['title']}' the ruler ordered: {label} - it "
                           f"{'worked' if worked else 'went wrong'}: {note}{fate}")
        self.reveal.append(f"'{label}': it {'WORKED' if worked else 'WENT WRONG'} - {note}{fate}")
        self.b.log(f"  battle order: {label} - {'worked' if worked else 'went wrong'} ({chance}%)"
                   + (f"; effects: {', '.join(self._describe(e) for e in effects)}" if effects else "") + fate)
        self._go(lines)

