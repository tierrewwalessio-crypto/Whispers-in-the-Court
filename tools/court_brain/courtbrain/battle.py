    def _finish(self) -> None:
        """The battle is over: stop the reports, clear the orders, tell how it ended."""
        self.b.mail.send(["votc_battle_end = yes"], label="battle:end")
        last, first = self.field, self.first
        if last is None or first is None:
            self.reset()
            return
        us, them = last.sides(self.ours)
        won = self._we_won(us, them)
        result = ("WE WON: the enemy broke and left the field." if won is True else
                  "WE LOST: our army broke and left the field." if won is False else
                  "It ended without a clear rout - both sides drew apart.")
        reveal = ""
        if self.reveal:
            reveal = "HOW THE LAST ORDERS WENT (secret until now):\n" + "\n".join(f"- {r}" for r in self.reveal)
        task = AFTER_TASK.format(style=prompts.text("battle_narrator"), result=result, first=self._field_text(first),
                                 last=self._field_text(last), so_far=self._so_far(), reveal=reveal,
                                 reveal_rule_short="including how the last orders went" if reveal else "as they were",
                                 lang=self._lang(), player=prompts.player_block("battles", "narration", "avoid"))
        try:
            data = self._ask(task, AFTER_SCHEMA, "votc_battle_after", 3000, guide="battle_end")
        except Player2Error as exc:
            self.b.log(f"Account of the battle not written: {exc}")
            data = {}
        title = str(data.get("title") or self.title)[:70]
        body = str(data.get("body") or "").strip()[:2600]
        note = str(data.get("memory_note") or "").strip()[:400] or (
            f"{self.title}: {us.country} against {them.country} at {last.place} - "
            + ("victory" if won else "defeat" if won is False else "no clear result")
            + f"; our losses about {_men(us.losses)}, theirs {_men(them.losses)}.")
        mem = self.b.memory
        if mem is not None and body:
            mem.add_page(last.date, "battle", title, body)
        self.b._war_fact(last.date, f"battle: {note}")          # the court's memory and the book of the reign
        if body:
            self.b.last_scene = {"title": title, "body": body, "kind": "battle"}
            self.b.mail.send(["votc_battle_show_end = yes"],
                             loc={"votc_bt_end_title": title, "votc_bt_end_body": with_gist(data.get("gist"), body)},
                             label="battle:after")
        self.b.log(f"Battle over: {note}")
        self.reset()

    @staticmethod
    def _we_won(us: Side, them: Side) -> bool | None:
        a, b = us.morale, them.morale
        if a is None or b is None:
            return None
        if b <= 0.2 and a > b:
            return True
        if a <= 0.2 and b > a:
            return False
        if abs(a - b) < 0.1:
            return None
        return a > b

    # ------------------------------------------------------------- the panel
    def on_close(self, session: Any) -> None:
        if session is not self.session:
            return
        self.session = None
        if self.waiting in ("plan", "order"):
            self.leave()

    def on_hub(self, key: str) -> None:
        if key == "battle:leave":
            self.b._ui("close")
            if self.b.session is self.session:
                self.b.session = None
            self.session = None
            self.leave()
