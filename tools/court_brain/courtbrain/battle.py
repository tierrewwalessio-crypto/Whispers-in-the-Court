def modifier_key(lever: str, up: bool, level: int) -> str:
    return f"votc_bm_{lever}_{'up' if up else 'down'}{level}"


def all_modifiers():
    """(key, shown name, [(modifier type, value)]) for every modifier the mod defines."""
    for lever, (good, bad, parts) in LEVERS.items():
        for up in (True, False):
            for level in (1, 2, 3):
                vals = [(t, v[level - 1] if up else -v[level - 1]) for t, v in parts]
                yield modifier_key(lever, up, level), (good if up else bad) + " " + "I" * level, vals


