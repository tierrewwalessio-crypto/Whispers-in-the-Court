_NUM = re.compile(r"-?\d[\d,.]*\s*[kKmM]?")


def _num(raw: str | None) -> float | None:
    """'12,400' '12.4K' '0.62' '62%' -> a number; None when unresolved or empty."""
    if raw is None:
        return None
    text = str(raw).strip()
    if not text or "[" in text:
        return None
    m = _NUM.search(text.replace(" ", ""))
    if not m:
        return None
    tok = m.group(0).replace(" ", "")
    mult = 1.0
    if tok[-1] in "kK":
        mult, tok = 1000.0, tok[:-1]
    elif tok[-1] in "mM":
        mult, tok = 1_000_000.0, tok[:-1]
    if "," in tok and "." in tok:
        tok = tok.replace(",", "")
    elif "," in tok:
        # "12,400" thousands; "0,62" a decimal comma
        head, _, tail = tok.partition(",")
        tok = tok.replace(",", "") if len(tail) == 3 else head + "." + tail
    try:
        value = float(tok) * mult
    except ValueError:
        return None
    if text.endswith("%"):
        value /= 100.0
    return value


def _frac(raw: str | None) -> float | None:
    """A morale reading as 0..1, whether the game wrote 0.62 or 62."""
    v = _num(raw)
    if v is None:
        return None
    return v / 100.0 if v > 1.5 else v


def _text(raw: str | None) -> str:
    text = (raw or "").strip()
    return "" if "[" in text else text


@dataclass
class Side:
    tag: str = ""
    country: str = ""
    player: bool = False
    commander: str = ""
    mil: float | None = None
    morale: float | None = None          # 0..1 of the side's full morale
    men: float | None = None             # men in the fighting line
    visual: float | None = None          # all men on the field
    losses: float | None = None
    prisoners: float | None = None
    dice: float | None = None
    left: float | None = None
    center: float | None = None
    right: float | None = None
    left_m: float | None = None
    center_m: float | None = None
    right_m: float | None = None
    reserve: float | None = None

    @classmethod
    def of(cls, rec: Record) -> "Side":
        f = rec.fields
        return cls(
            tag=_text(f.get("tag")), country=_text(f.get("country")), player=_text(f.get("player")) == "1",
            commander=_text(f.get("cmd")), mil=_num(f.get("mil")), morale=_frac(f.get("morale")),
            men=_num(f.get("men")), visual=_num(f.get("all")), losses=_num(f.get("losses")),
            prisoners=_num(f.get("prisoners")), dice=_num(f.get("dice")),
            left=_num(f.get("left")), center=_num(f.get("center")), right=_num(f.get("right")),
            left_m=_frac(f.get("leftm")), center_m=_frac(f.get("centerm")), right_m=_frac(f.get("rightm")),
            reserve=_num(f.get("reserve")),
        )

    def total(self) -> float:
        return (self.visual if self.visual is not None else (self.men or 0) + (self.reserve or 0)) or 0


@dataclass
class Field:
    name: str = ""
    date: str = ""
    active: bool = True
    naval: bool = False
    bombard: bool = False
    frontage: float | None = None
    place: str = ""
    province: str = ""
    topography: str = ""
    vegetation: str = ""
    climate: str = ""
    river: bool = False
    owner: str = ""
    gone: bool = False                   # the bridge found no battle there any more
    att: Side = field(default_factory=Side)
    dfn: Side = field(default_factory=Side)
    census: dict[str, float] = field(default_factory=dict)
    raw: list[str] = field(default_factory=list)

    @property
    def valid(self) -> bool:
        return bool(self.place) and self.active and (self.att.men is not None or self.dfn.men is not None)

    def sides(self, ours: str) -> tuple[Side, Side]:
        return (self.att, self.dfn) if ours == "att" else (self.dfn, self.att)


class _Reading:
    """The records of one report of the field, as they come in."""

    def __init__(self) -> None:
        self.field = Field()

    def feed(self, rec: Record) -> None:
        f = rec.fields
        if rec.kind == "BATTLE":
            self.field = Field(
                name=_text(f.get("name")), date=_text(f.get("date")), active=_text(f.get("active")) != "0",
                naval=_text(f.get("naval")) == "1", bombard=_text(f.get("bombard")) == "1",
                frontage=_num(f.get("frontage")), place=_text(f.get("loc")), province=_text(f.get("province")),
                topography=_text(f.get("topo")), vegetation=_text(f.get("veg")), climate=_text(f.get("climate")),
                river=_text(f.get("river")) == "1", owner=_text(f.get("owner")),
                gone=_text(f.get("gone")) == "1")
        elif rec.kind == "BSIDE":
            side = Side.of(rec)
            if rec.at(0) == "att":
                self.field.att = side
            else:
                self.field.dfn = side
        elif rec.kind == "BCENSUS":
            self.field.census = {k: v for k, v in ((k, _num(x)) for k, x in f.items()) if v is not None}
        self.field.raw.append(rec.raw[:400])


def _short(text: str, limit: int) -> str:
    """A line cut at a word, never mid-word; labels such as 'Cautious plan:' dropped."""
    text = re.sub(r"^\s*[\w' ]{3,24}:\s+", "", text.strip()) if re.match(r"^\s*[\w' ]{3,24}:\s+\S", text) else text.strip()
    if len(text) <= limit:
        return text
    cut = text[:limit].rsplit(" ", 1)[0].rstrip(",;:")
    return cut + "…"


def _hours(date: str) -> int:
    """Hours since year 0, for a date the bridge wrote ('08:00, 1 April, 1337')."""
    p = gamedate.parse(date)
    if p is None:
        return 0
    hour = re.search(r"\b(\d{1,2}):\d{2}\b", date or "")
    return ((p[0] * 365 + p[1] * 30 + p[2]) * 24) + (int(hour.group(1)) if hour else 0)


def _men(v: float | None) -> str:
    if v is None:
        return "unknown"
    return f"{int(round(v)):,}"


def _morale_words(v: float | None) -> str:
    if v is None:
        return "unknown"
    for limit, words in ((0.12, "breaking - men already running"), (0.3, "badly shaken"),
                         (0.5, "worn and uncertain"), (0.7, "holding, but tiring"), (0.9, "firm"),
                         (9.0, "fresh and eager")):
        if v <= limit:
            return words
    return "fresh"


def _width_words(frontage: float | None, men: float) -> str:
    """How much of an army the ground lets fight at once - in words."""
    if not frontage:
        return "unknown"
    room = frontage * 1000                 # a company is about a thousand men at full strength
    if men and men > room * 1.3:
        return "narrow for armies this size: many must wait their turn behind the fighting line"
    if frontage <= 12:
        return "narrow ground: the lines cannot spread far"
    if frontage <= 24:
        return "room enough for both lines to deploy"
    return "wide open ground, where a longer line can wrap around a shorter one"


def _skill_words(v: float | None) -> str:
    if v is None:
        return ""
    v = v if v > 10 else v * 10          # abilities are 0-100; old saves may say 0-10
    for limit, words in ((20, "a poor general"), (40, "a middling general"), (60, "a capable general"),
                         (80, "a very able general"), (101, "a brilliant general")):
        if v < limit:
            return words
    return ""


