"""Commanding a battle in person.

    the player opens a battle and presses "Command the battle" ─► the game
        pauses and the bridge sends the field as it stands (both sides, the
        wings and the reserves, the men, the commanders, the ground)
    the side panel opens on it: a narrator outside the battle sets the scene
        with the true numbers, and the ruler gives the plan in their own words
    the plan is judged against the field ─► small bonuses or penalties land on
        the armies there, and the game runs again at the slowest speed
    while it runs the bridge reports the field every second or so; at the
        moments that matter (the first clash, a wing giving way, a long grind,
        the edge of a rout) the game pauses and a moment of the battle comes
        up: three orders whose effect nobody knows yet, or the ruler's own
    the choice is rolled at once and applied, the game runs on, and how it
        went is told by the next moment - or by the account of the battle
        when it ends

Everything the game is told goes through the mod's own effects
(in_game/common/scripted_effects/votc_battle_effects.txt, generated by
tools/gen_battle.py from LEVERS below), so the AI never writes script.
"""

