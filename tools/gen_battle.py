#!/usr/bin/env python3
"""Generate the mod's side of "Command the battle" (see courtbrain/battle.py).

Writes, from battle.LEVERS so that the two can never disagree:
  main_menu/common/static_modifiers/votc_battle_modifiers.txt   the unit modifiers
  in_game/common/scripted_effects/votc_battle_effects.txt      what a mail may call
  in_game/common/script_values/votc_battle_values.txt          the troops on the field
  main_menu/localization/english/votc_battle_l_english.yml     names and texts
and the bridge's commands in votc_bridge_l_english.yml (the field's report).

    python tools/gen_battle.py
"""

from __future__ import annotations

import io
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MOD = ROOT / "mod" / "WhispersInTheCourt"
sys.path.insert(0, str(ROOT / "tools" / "court_brain"))

from courtbrain.battle import LEVERS, all_modifiers  # noqa: E402

BOM = "﻿"
MODIFIERS = MOD / "main_menu/common/static_modifiers/votc_battle_modifiers.txt"
EFFECTS = MOD / "in_game/common/scripted_effects/votc_battle_effects.txt"
VALUES = MOD / "in_game/common/script_values/votc_battle_values.txt"
LOC = MOD / "main_menu/localization/english/votc_battle_l_english.yml"
BRIDGE = MOD / "main_menu/localization/english/votc_bridge_l_english.yml"
DYNAMIC = MOD / "main_menu/localization/english/votc_dynamic_l_english.yml"

HEAD = "# Whispers in the Court - commanding a battle. GENERATED by tools/gen_battle.py: edit there.\n"


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    io.open(path, "w", encoding="utf-8", newline="\n").write(BOM + text)


def fmt(v: float) -> str:
    return (f"{v:.3f}".rstrip("0").rstrip(".")) if isinstance(v, float) else str(v)


# ---------------------------------------------------------------- modifiers
def modifiers_text() -> str:
    out = [HEAD, "# Short, and only while the battle lasts: the ruler's orders, well or badly given.", ""]
    for key, _name, vals in all_modifiers():
        out.append(f"{key} = {{")
        out.append("\tgame_data = { category = unit }")
        for t, v in vals:
            out.append(f"\t{t} = {fmt(v)}")
        out.append("}")
    out += ["", "# The ruler took a wound in the fighting.", "votc_battle_wound = {",
            "\tgame_data = { category = character }", "\tadm = -5", "\tdip = -5", "\tmil = -10", "}", ""]
    return "\n".join(out)


# ------------------------------------------------------------------ effects
KINDS = {
    "inf": ("army_light_infantry", "army_heavy_infantry"),
    "cav": ("army_light_cavalry", "army_heavy_cavalry"),
    "art": ("army_artillery",),
    "aux": ("army_auxiliary",),
}
SIDES = {
    "own": "owner = root",
    "foe": "owner = { is_at_war_with = root }",
    "ally": "NOT = { owner = root } NOT = { owner = { is_at_war_with = root } }",
}


def effects_text() -> str:
    strip = "\n".join(f"\tremove_unit_modifier = {key}" for key, _n, _v in all_modifiers())
    return HEAD + f"""#
# Everything here runs with root = the player's country (a mail, or a console
# command from the bridge). var:votc_bloc is the location of the battle.
# EU5 does not let an effect read back a variable it set a moment ago: every
# flag below is set by one command and read by a later one.

# The player took command (the "Command the battle" button in the battle
# window, or the army's ability): the button already paused the game; the
# bridge runs this as a console command, so that root is the country.
votc_battle_take = {{
	remove_variable = votc_sig_btake
	set_variable = {{ name = votc_bt_live value = 1 }}
	set_variable = {{ name = votc_bt_hold value = 1 }}
	set_variable = {{ name = votc_bt_a value = 1 }}
	votc_prepare_context = yes
	set_variable = {{ name = votc_sig_battle value = 1 }}
}}

# The report loop: each report hands over to the other flag, which starts the
# bridge's next report (see votc_bridge.gui). A kick is the same hand-over.
votc_battle_flip = {{
	if = {{
		limit = {{ has_variable = votc_bt_live NOT = {{ exists = var:votc_bloc }} }}
		remove_variable = votc_bt_live
	}}
	else_if = {{
		limit = {{ has_variable = votc_bt_live }}
		if = {{
			limit = {{ has_variable = votc_bt_a }}
			remove_variable = votc_bt_a
			set_variable = {{ name = votc_bt_b value = 1 }}
		}}
		else = {{
			remove_variable = votc_bt_b
			set_variable = {{ name = votc_bt_a value = 1 }}
		}}
	}}
}}
votc_battle_kick = {{
	votc_battle_flip = yes
}}

# Pause (a moment of the battle is being written) and run again, at speed 1.
votc_battle_hold = {{
	set_variable = {{ name = votc_bt_hold value = 1 }}
}}
votc_battle_go = {{
	remove_variable = votc_bt_hold
	set_variable = {{ name = votc_bt_go value = 1 }}
}}

# The orders, well or badly given: on our men there, or on the enemy's.
votc_battle_mod = {{
	var:votc_bloc ?= {{
		every_unit_in_location = {{
			limit = {{ owner = root in_combat = yes }}
			add_unit_modifier = {{ modifier = $mod$ days = $days$ mode = add_and_extend }}
		}}
	}}
}}
votc_battle_foe_mod = {{
	var:votc_bloc ?= {{
		every_unit_in_location = {{
			limit = {{ owner = {{ is_at_war_with = root }} in_combat = yes }}
			add_unit_modifier = {{ modifier = $mod$ days = $days$ mode = add_and_extend }}
		}}
	}}
}}

# Blows struck at once.
votc_battle_shake_own = {{
	var:votc_bloc ?= {{ every_unit_in_location = {{ limit = {{ owner = root in_combat = yes }} damage_unit_morale_percent = $p$ }} }}
}}
votc_battle_shake_foe = {{
	var:votc_bloc ?= {{ every_unit_in_location = {{ limit = {{ owner = {{ is_at_war_with = root }} in_combat = yes }} damage_unit_morale_percent = $p$ }} }}
}}
votc_battle_bleed_own = {{
	var:votc_bloc ?= {{ every_unit_in_location = {{ limit = {{ owner = root in_combat = yes }} damage_unit_percent = $p$ }} }}
}}
votc_battle_bleed_foe = {{
	var:votc_bloc ?= {{ every_unit_in_location = {{ limit = {{ owner = {{ is_at_war_with = root }} in_combat = yes }} damage_unit_percent = $p$ }} }}
}}
votc_battle_rally = {{
	var:votc_bloc ?= {{ every_unit_in_location = {{ limit = {{ owner = root in_combat = yes }} add_morale = $p$ }} }}
}}

# The ruler rode where the fighting was.
votc_battle_wound_ruler = {{
	ruler ?= {{
		add_character_modifier = {{ modifier = votc_battle_wound years = 3 mode = add_and_extend }}
	}}
}}
votc_battle_fall_ruler = {{
	ruler ?= {{ save_scope_as = votc_fallen }}
	if = {{
		limit = {{ exists = scope:votc_fallen }}
		kill_character = {{ target = scope:votc_fallen reason = combat }}
	}}
}}

# What the player sees.
votc_battle_moment = {{
	trigger_event_non_silently = votc.600
}}
votc_battle_show_end = {{
	trigger_event_non_silently = votc.610
}}

# An answer to a moment of the battle (votc.600): 1-3, or 4 for the ruler's own order.
votc_battle_choose = {{
	set_variable = {{ name = votc_bt_choice value = $n$ }}
	set_variable = {{ name = votc_sig_bchoice value = 1 }}
}}

# The battle is over (or nobody commands it any more): the orders fade with it.
votc_bm_strip = {{
{strip}
}}
votc_battle_end = {{
	every_unit = {{ votc_bm_strip = yes }}
	var:votc_bloc ?= {{
		every_unit_in_location = {{
			limit = {{ NOT = {{ owner = root }} }}
			votc_bm_strip = yes
		}}
	}}
	remove_variable = votc_bt_live
	remove_variable = votc_bt_a
	remove_variable = votc_bt_b
	remove_variable = votc_bt_hold
}}
"""


def values_text() -> str:
    out = [HEAD, "# The troops fighting on the field of var:votc_bloc, by kind and side, as the",
           "# sum of their companies' strength (Court Brain turns it into shares of the",
           "# men each side has there). Evaluated on the player's country.", ""]
    for side, cond in SIDES.items():
        for kind, cats in KINDS.items():
            test = " ".join(f"sub_unit_category = sub_unit_category:{c}" for c in cats)
            if len(cats) > 1:
                test = f"OR = {{ {test} }}"
            out += [f"votc_v_bc_{side}_{kind} = {{",
                    "\tvalue = 0",
                    "\tvar:votc_bloc ?= {",
                    "\t\tevery_unit_in_location = {",
                    f"\t\t\tlimit = {{ {cond} in_combat = yes }}",
                    "\t\t\tevery_sub_unit = {",
                    f"\t\t\t\tlimit = {{ {test} }}",
                    "\t\t\t\tadd = subunit_strength",
                    "\t\t\t}",
                    "\t\t}",
                    "\t}",
                    "}"]
    out += ["votc_v_bt_choice = { value = 0 if = { limit = { has_variable = votc_bt_choice } add = var:votc_bt_choice } round = yes }", ""]
    return "\n".join(out)


# --------------------------------------------------------------------- loc
