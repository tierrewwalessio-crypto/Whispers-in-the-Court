# ------------------------------------------------------------------ bridge
# EVERY read of the combat must be guarded by HasCombat on the location, as the
# game's own interface does: reading a combat that has ended crashes the game.
# The bridge chooses between the key below and its "gone" twin with
# Select_CString, so the guarded key is never even localised without a combat.
LOCN = "GetPlayer.MakeScope.GetVariable('votc_bloc').GetLocation"
C = LOCN + ".GetCombat"
HAS = LOCN + ".HasCombat"


def _yes(expr: str) -> str:
    return f"[Select_CString({expr}, '1', '0')]"


def battle_lines() -> list[str]:
    lines = [
        "votc_say BATTLE"
        f"|name=[{C}.GetNameWithNoTooltip]|date=[GetDateString]|active={_yes(C + '.IsActive')}"
        f"|naval={_yes(C + '.IsNavalCombat')}|bombard={_yes(C + '.IsInBombardPhase')}"
        f"|frontage=[{LOCN}.GetModifierValue('local_frontage_allowed')]"
        f"|loc=[{LOCN}.GetNameWithNoTooltip]|province=[{LOCN}.GetProvince.GetNameWithNoTooltip]"
        f"|topo=[{LOCN}.GetTopography.GetNameWithNoTooltip]"
        f"|veg=[{LOCN}.GetVegetation.GetNameWithNoTooltip]"
        f"|climate=[{LOCN}.GetClimate.GetNameWithNoTooltip]|river={_yes(LOCN + '.HasRiver')}"
        f"|owner=[{LOCN}.GetOwner.GetNameWithNoTooltip]"]
    for key, getter in (("att", "GetAttacker"), ("def", "GetDefender")):
        s = f"{C}.{getter}"
        lines.append(
            f"votc_say BSIDE|{key}|tag=[{s}.GetCountry.GetTag]|country=[{s}.GetCountry.GetNameWithNoTooltip]"
            f"|player={_yes(s + '.IsPlayerInCombat')}|cmd=[{s}.GetCommander.GetNameWithNoTooltip]"
            f"|mil=[{s}.GetCommander.GetAbility('mil')]|morale=[{s}.GetMoralePercent]"
            f"|men=[{s}.GetEngagedUnitsStrength]|all=[{s}.GetVisualStrength]"
            f"|losses=[{s}.GetBattleSide.GetLosses]|prisoners=[{s}.GetBattleSide.GetTotalImprisoned]"
            f"|dice=[{s}.GetDiceWithModifiers]"
            f"|left=[{s}.GetLeft.GetEngagedStrength]|leftm=[{s}.GetLeft.GetMoralePercentage]"
            f"|center=[{s}.GetCenter.GetEngagedStrength]|centerm=[{s}.GetCenter.GetMoralePercentage]"
            f"|right=[{s}.GetRight.GetEngagedStrength]|rightm=[{s}.GetRight.GetMoralePercentage]"
            f"|reserve=[{s}.GetReserves.GetNonEngagedStrength]")
    census = "|".join(f"{side}_{kind}=[GetPlayer.MakeScope.ScriptValue('votc_v_bc_{side}_{kind}')|2]"
                      for side in SIDES for kind in KINDS)
    lines.append("votc_say BCENSUS|" + census)
    return lines


def patch_bridge() -> None:
    text = io.open(BRIDGE, encoding="utf-8-sig").read()
    hub = re.search(r' votc_emit_hub:0 "(votc_say SIG\|hub\|.*)"', text).group(1)
    cmds = hub.split(";")
    cmds[0] = cmds[0].replace("SIG|hub", "SIG|battle")
    end = next(i for i, c in enumerate(cmds) if c.startswith("votc_say END|"))
    realm = cmds[:end]                              # the picture of the realm, as the hub sends it
    gone = ["votc_say BATTLE|gone=1|date=[GetDateString]"]
    cmds = realm + battle_lines() + ["votc_say END|battle", "effect remove_variable = votc_sig_battle"]
    cmds_gone = realm + gone + ["votc_say END|battle", "effect remove_variable = votc_sig_battle"]
    new = {
        "votc_emit_battle": ";".join(cmds),
        "votc_emit_battle_gone": ";".join(cmds_gone),
        "votc_emit_bgone": ";".join(gone + ["votc_say END|bstate", "effect votc_battle_flip = yes", "run votc_poll.txt"]),
        "votc_emit_bstate": ";".join(battle_lines() + ["votc_say END|bstate", "effect votc_battle_flip = yes",
                                                        "run votc_poll.txt"]),
        "votc_emit_bchoice": ("votc_say BCHOICE|n=[GetPlayer.MakeScope.ScriptValue('votc_v_bt_choice')|0];"
                              "effect remove_variable = votc_sig_bchoice"),
        "votc_cmd_btake": "effect votc_battle_take = yes",
        "votc_cmd_bgo_done": "effect remove_variable = votc_bt_go",
    }
    for key, value in new.items():
        line = f' {key}:0 "{value}"'
        pat = re.compile(rf"^ {key}:0 \".*\"$", re.M)
        if pat.search(text):
            text = pat.sub(lambda _m: line, text)
        else:
            text = text.rstrip("\n") + "\n" + line + "\n"
    io.open(BRIDGE, "w", encoding="utf-8-sig", newline="\n").write(text)


def patch_dynamic() -> None:
    text = io.open(DYNAMIC, encoding="utf-8-sig").read()
    wanted = {
        "votc_bt_title": "The Battle",
        "votc_bt_body": "The battle goes on.",
        "votc_bt_opt1": "Hold the line.",
        "votc_bt_opt2": "Commit the reserve.",
        "votc_bt_opt3": "Send the horse around their flank.",
        "votc_bt_end_title": "After the Battle",
        "votc_bt_end_body": "The field is quiet.",
    }
    for key, value in wanted.items():
        if not re.search(rf"^ {key}:0 ", text, re.M):
            text = text.rstrip("\n") + f'\n {key}:0 "{value}"\n'
    io.open(DYNAMIC, "w", encoding="utf-8-sig", newline="\n").write(text)


if __name__ == "__main__":
    write(MODIFIERS, modifiers_text())
    write(EFFECTS, effects_text())
    write(VALUES, values_text())
    write(LOC, loc_text())
    patch_bridge()
    patch_dynamic()
    print(f"{sum(1 for _ in all_modifiers())} modifiers, {len(LEVERS)} levers; effects, values, loc and bridge written.")
